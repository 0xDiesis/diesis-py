def _verify(case: dict[str, Any], response: dict[str, Any], block_hash: str, **overrides: Any) -> Any:
    request = case["request"]
    arguments: dict[str, Any] = {
        "block_number": int(request["blockNumber"], 16),
        "address": request["address"],
        "storage_keys": request["storageKeys"],
        "trusted_block_hash": block_hash,
    }
    arguments.update(overrides)
    return verify_state_proof(response, **arguments)


def _tamper(hex_value: str) -> str:
    data = bytearray(bytes.fromhex(hex_value[2:]))
    data[len(data) // 2] ^= 1
    return "0x" + data.hex()


def test_real_vector_returns_the_values_the_node_verifier_authenticated() -> None:
    verified = _verify(REAL, REAL["response"], REAL["expectedBlockHash"])
    expected = REAL["expected"]
    assert verified.block_number == int(expected["blockNumber"])
    assert verified.timestamp == int(expected["timestamp"])
    assert verified.state_root == expected["stateRoot"]
    assert verified.account is not None
    assert verified.account.nonce == int(expected["account"]["nonce"])
    assert verified.account.balance == int(expected["account"]["balance"])
    assert verified.account.code_hash == expected["account"]["codeHash"]
    assert verified.account.storage_root == expected["account"]["storageRoot"]
    assert [(s.slot, s.value) for s in verified.storage] == [(s["slot"], int(s["value"])) for s in expected["storage"]]


def test_real_vector_rejects_an_untrusted_block_hash_or_root() -> None:
    with pytest.raises(StateProofError, match="trusted block"):
        _verify(REAL, REAL["response"], "0x" + "aa" * 32)
    response = copy.deepcopy(REAL["response"])
    response["stateRoot"] = "0x" + "bb" * 32
    with pytest.raises(StateProofError, match="trusted block"):
        _verify(REAL, response, REAL["expectedBlockHash"])
    with pytest.raises(StateProofError, match="trusted block"):
        _verify(REAL, REAL["response"], REAL["expectedBlockHash"], block_number=3)


