# --- Hand-built nodes for canonical-form rules -------------------------------


def _rlp_string(data: bytes) -> bytes:
    if len(data) == 1 and data[0] < 0x80:
        return data
    if len(data) < 56:
        return bytes([0x80 + len(data)]) + data
    size = len(data).to_bytes((len(data).bit_length() + 7) // 8, "big")
    return bytes([0xB7 + len(size)]) + size + data


def _rlp_list(items: list[bytes]) -> bytes:
    payload = b"".join(items)
    if len(payload) < 56:
        return bytes([0xC0 + len(payload)]) + payload
    size = len(payload).to_bytes((len(payload).bit_length() + 7) // 8, "big")
    return bytes([0xF7 + len(size)]) + size + payload


def _rlp_int(value: int) -> bytes:
    return _rlp_string(value.to_bytes((value.bit_length() + 7) // 8, "big"))


def _leaf(nibbles: list[int], value: bytes) -> bytes:
    odd = len(nibbles) % 2
    flat = [3, *nibbles] if odd else [2, 0, *nibbles]
    path = bytes(flat[i] * 16 + flat[i + 1] for i in range(0, len(flat), 2))
    return _rlp_list([_rlp_string(path), _rlp_string(value)])


def _key(data: bytes) -> list[int]:
    return [n for b in keccak(data) for n in (b >> 4, b & 15)]


def _header(root: bytes, number: int) -> bytes:
    fields = [b"\x01" * 32, b"\x02" * 32, b"\x00" * 20, root, b"\x00" * 32, b"\x00" * 32, b"\x00" * 256]
    encoded = [_rlp_string(f) for f in fields]
    encoded += [_rlp_int(0), _rlp_int(number), _rlp_int(30_000_000), _rlp_int(0), _rlp_int(1)]
    encoded += [_rlp_string(b""), _rlp_string(b"\x03" * 32), _rlp_string(b"\x00" * 8), _rlp_int(7)]
    return _rlp_list(encoded)


def _single_account_case(account_nodes: list[bytes], storage_root: str, slot_nodes: list[bytes], value: str) -> Any:
    address = "0x" + "46" * 20
    slot = "0x" + "31" * 32
    header = _header(keccak(account_nodes[0]), 1)
    block_hash = "0x" + keccak(header).hex()
    response = {
        "schemaVersion": 2,
        "blockHash": block_hash,
        "stateRoot": "0x" + keccak(account_nodes[0]).hex(),
        "canonicalHeader": "0x" + header.hex(),
        "checkpoint": "0x4d50513700",
        "proof": {
            "address": address,
            "nonce": "0x0",
            "balance": "0x0",
            "codeHash": EMPTY_CODE_HASH,
            "storageHash": storage_root,
            "accountProof": ["0x" + n.hex() for n in account_nodes],
            "storageProof": [{"key": slot, "value": value, "proof": ["0x" + n.hex() for n in slot_nodes]}],
        },
    }
    return lambda: verify_state_proof(
        response, block_number=1, address=address, storage_keys=[slot], trusted_block_hash=block_hash
    )


def _account(storage_root: bytes) -> bytes:
    return _rlp_list(
        [_rlp_int(0), _rlp_int(0), _rlp_string(storage_root), _rlp_string(bytes.fromhex(EMPTY_CODE_HASH[2:]))]
    )


def test_rejects_an_included_zero_storage_leaf() -> None:
    slot_key = _key(bytes.fromhex("31" * 32))
    present = _leaf(slot_key, _rlp_int(9))
    zero = _leaf(slot_key, b"\x80")
    account_key = _key(bytes.fromhex("46" * 20))
    for storage_leaf, value, ok in [(present, "0x9", True), (zero, "0x0", False)]:
        storage_root = keccak(storage_leaf)
        check = _single_account_case(
            [_leaf(account_key, _account(storage_root))], "0x" + storage_root.hex(), [storage_leaf], value
        )
        if ok:
            assert check().storage[0].value == 9
        else:
            with pytest.raises(StateProofError, match="storage encoding"):
                check()


def test_rejects_a_one_child_branch() -> None:
    account_key = _key(bytes.fromhex("46" * 20))
    leaf = _leaf(account_key[1:], _account(bytes.fromhex(EMPTY_ROOT_HASH[2:])))
    sibling = _leaf(
        account_key[1:], _rlp_list([_rlp_int(1), _rlp_int(0), _rlp_string(b"\x00" * 32), _rlp_string(b"\x00" * 32)])
    )
    empty = _rlp_string(b"")

    def branch(children: dict[int, bytes]) -> bytes:
        return _rlp_list([_rlp_string(keccak(children[n])) if n in children else empty for n in range(16)] + [empty])

    other = (account_key[0] + 1) % 16
    canonical = _single_account_case([branch({account_key[0]: leaf, other: sibling}), leaf], EMPTY_ROOT_HASH, [], "0x0")
    assert canonical().storage[0].value == 0
    lonely = _single_account_case([branch({account_key[0]: leaf}), leaf], EMPTY_ROOT_HASH, [], "0x0")
    with pytest.raises(StateProofError, match="proof path"):
        lonely()


