def test_client_requests_and_parses_the_state_proof() -> None:
    request = REAL["request"]
    with patch("diesis.client.Web3") as mock:
        mock.return_value.provider.make_request.return_value = {"result": REAL["response"]}
        client = DiesisClient("https://rpc.diesis.xyz")
        proof = client.get_state_proof(int(request["blockNumber"], 16), request["address"], request["storageKeys"])
        assert proof == REAL["response"]
        mock.return_value.provider.make_request.assert_called_with("diesis_getStateProof", [request])
        with pytest.raises(StateProofError, match="state proof response"):
            client.get_state_proof(2, "0x" + "12" * 20, request["storageKeys"])
        with pytest.raises(StateProofError, match="storage keys"):
            client.get_state_proof(2, request["address"], ["0x01"])
        assert not hasattr(client, "get_block_witness")


